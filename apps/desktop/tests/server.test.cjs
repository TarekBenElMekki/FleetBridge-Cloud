'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {makeServer}=require('../server'),{createStore}=require('../store');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
test('pair two Chrome profiles and sync into same database',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'fleetbridge-server-test-'));t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const app=makeServer({port:0,store:createStore(dir)}),address=await app.listen();t.after(()=>app.close());
  const base=`http://127.0.0.1:${address.port}`,origin='chrome-extension://aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa';
  const home=await fetch(base+'/');assert.equal(home.status,200);
  assert.match(await home.text(),/corporate\.css/);
  const classic=await fetch(base+'/classic-crm.css');assert.equal(classic.status,200);
  assert.match(await classic.text(),/Inter,'Segoe UI'/);
  const corporate=await fetch(base+'/corporate.css');assert.equal(corporate.status,200);
  assert.match(corporate.headers.get('content-type'),/text\/css/);
  const atlas=await fetch(base+'/atlas/index.html');assert.equal(atlas.status,200);
  assert.match(await atlas.text(),/candidate-locations\.js/);
  const atlasData=await fetch(base+'/atlas/data.json');assert.equal(atlasData.status,200);
  assert.match(atlasData.headers.get('content-type'),/application\/json/);
  assert.equal((await atlasData.json()).operators.length,418);
  const geo=await fetch(base+'/atlas/europe-base.geojson');assert.equal(geo.status,200);
  assert.match(geo.headers.get('content-type'),/application\/geo\+json/);
  const logoList=await (await fetch(base+'/atlas/logo-manifest.json')).json();assert.ok(Object.keys(logoList.groups).length>10);
  const code=(await (await fetch(base+'/api/pair-code')).json()).code;
  const headers={Origin:origin,'Content-Type':'application/json'};
  const pair=await fetch(base+'/api/pair',{method:'POST',headers,body:JSON.stringify({code,label:'Profile A'})});
  assert.equal(pair.status,200);const {token}=await pair.json();assert.equal(token.length,64);
  const item={url:'https://www.linkedin.com/in/mechanic-1',title:'Technician'};
  const send=await fetch(base+'/api/sync',{method:'POST',headers:{...headers,Authorization:'Bearer '+token},body:JSON.stringify({records:[item]})});
  assert.equal(send.status,200);assert.equal((await (await fetch(base+'/api/candidates')).json()).records.length,1);
  const employerProspect=await fetch(base+'/api/atlas-prospect',{method:'POST',headers:{'Content-Type':'application/json',Origin:base},body:JSON.stringify({id:'ratp-example',updates:{status:'Contacted',notes:'Follow up next week'}})});
  assert.equal(employerProspect.status,200);
  const saved=await (await fetch(base+'/api/atlas-prospects')).json();
  assert.equal(saved.statuses['ratp-example'],'Contacted');assert.equal(saved.notes['ratp-example'],'Follow up next week');
  const manualPin={id:'custom-depot123',name:'Verified workshop example',city:'Lille',code:'FR',lat:50.63,lng:3.06,type:'depot',origin:'manual'};
  const savePin=await fetch(base+'/api/atlas-custom',{method:'POST',headers:{'Content-Type':'application/json',Origin:base},body:JSON.stringify({records:[manualPin]})});
  assert.equal(savePin.status,200);
  assert.equal((await (await fetch(base+'/api/atlas-custom')).json()).records.length,1);
  const backup=await (await fetch(base+'/api/export')).json();
  assert.equal(backup.atlasCustom.length,1);
  assert.equal(backup.atlasProspects.statuses['ratp-example'],'Contacted');
  const nextCode=(await (await fetch(base+'/api/pair-code')).json()).code;
  const two=await fetch(base+'/api/pair',{method:'POST',headers,body:JSON.stringify({code:nextCode,label:'Profile B'})});
  assert.equal(two.status,200);const second=(await two.json()).token;
  const sendTwo=await fetch(base+'/api/sync',{method:'POST',headers:{...headers,Authorization:'Bearer '+second},body:JSON.stringify({records:[{...item,title:'Better description'}]})});
  assert.equal(sendTwo.status,200);assert.equal((await (await fetch(base+'/api/candidates')).json()).records.length,1);
  const bad=await fetch(base+'/api/sync',{method:'POST',headers:{...headers,Authorization:'Bearer '+'b'.repeat(64)},body:JSON.stringify({records:[item]})});
  assert.equal(bad.status,401);
  const website=await fetch(base+'/api/import',{method:'POST',headers:{...headers,Origin:'https://example.org'},body:JSON.stringify([item])});
  assert.equal(website.status,403);
});
